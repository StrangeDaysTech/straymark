let current: Locale = 'en';

/** Pick the active locale; unsupported values fall back to English. */
export function setLocale(locale: string): void {
  current = (SUPPORTED as string[]).includes(locale) ? (locale as Locale) : 'en';
  document.documentElement.lang = current;
}

/** Translate `key` in the active locale, interpolating `{var}` placeholders. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let value = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(`{${name}}`, String(replacement));
    }
  }
  return value;
}
